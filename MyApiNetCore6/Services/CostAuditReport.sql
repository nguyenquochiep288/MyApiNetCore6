CREATE TABLE #Issues(ROWKEY nvarchar(250),STOCK nvarchar(50),CODE nvarchar(50),NAME nvarchar(200),DEPOT nvarchar(200),
    VOUCHER nvarchar(250),VOUCHERID nvarchar(50),DETAILID nvarchar(50),DATE date,CREATED datetime2,VOUCHERDATE datetime2,
    QTY float,RATIO float,SMALLQTY decimal(28,6),START date,INITIAL decimal(28,6),[BEFORE] decimal(38,6),[AFTER] decimal(38,6),
    COST float,KIND int,TYPE varchar(20),REASON nvarchar(1000));
INSERT #Issues
SELECT CONCAT(b.STOCK,':',b.KIND,':',b.DETAILID,':',i.TYPE) AS ROWKEY,
    b.STOCK,b.CODE,b.NAME,b.DEPOT,b.VOUCHER,b.VOUCHERID,b.DETAILID,
    b.STAMP AS DATE,b.CREATED,b.VOUCHERDATE,b.QTY,b.RATIO,b.SMALLQTY,b.START,b.INITIAL,
    CASE WHEN b.BADCOUNT=0 THEN b.BALANCE-CASE WHEN b.KIND=2 THEN -b.SMALLQTY ELSE b.SMALLQTY END END AS [BEFORE],
    CASE WHEN b.BADCOUNT=0 THEN b.BALANCE END AS [AFTER],
    CASE WHEN i.TYPE='cost' AND b.KIND=1 THEN r.UNITCOST WHEN b.COSTED=1 THEN b.COST END AS COST,
    b.KIND,i.TYPE,i.REASON
FROM #Balance b
LEFT JOIN #ReturnTargets r ON b.KIND=1 AND r.STOCK=b.STOCK AND r.DETAILID=b.DETAILID
CROSS APPLY (VALUES
    ('invalid',b.INVALID),
    ('missing',CASE WHEN b.KIND=2 AND ISNULL(b.COSTED,0)=0 THEN N'Phiếu xuất chưa tính GIAVON' END),
    ('cost',CASE WHEN b.KIND=2 AND b.COSTED=1 AND (b.COST IS NULL OR b.COST<0) THEN N'Đã đánh dấu tính vốn nhưng GIAVON không hợp lệ'
        WHEN b.KIND=1 AND b.RETURNCOSTED=0 THEN
            CASE WHEN r.UNITCOST IS NOT NULL THEN N'Giá vốn ước tính theo bình quân trước khi nhập trả; cần đối chiếu dòng xuất gốc'
                 ELSE N'Khách trả thiếu dòng xuất gốc đã tính vốn và chưa xác định được giá vốn ước tính' END END),
    ('negative',CASE WHEN b.BADCOUNT=0 AND b.KIND=2 AND b.BALANCE<0 THEN N'Xuất vượt tồn tại thời điểm tính; kiểm tra đầu kỳ, nhập thiếu/sai kho và quy đổi' END),
    ('blocked',CASE WHEN b.BADCOUNT>0 AND b.INVALID IS NULL AND b.KIND=2 THEN N'Chưa đối chiếu được tồn vì lịch sử có dòng thiếu ngày/sai số lượng/quy đổi' END)
) i(TYPE,REASON)
WHERE i.REASON IS NOT NULL AND (b.STAMP IS NULL OR b.STAMP>=@Start);

-- One opening warning per stock with activity in the selected display period.
INSERT #Issues(ROWKEY,STOCK,CODE,NAME,DEPOT,START,INITIAL,TYPE,REASON)
SELECT CONCAT('opening:',s.ID),s.ID,s.MA,s.NAME,s.DEPOT,s.TUNGAY,s.INITIAL,'opening',
    N'Chưa khai báo đầu kỳ; tồn đối chiếu đang giả định bằng 0, chưa thể xác nhận giá vốn'
FROM #Scope s WHERE s.HASOPENING=0
    AND EXISTS(SELECT 1 FROM #Moves m WHERE m.STOCK=s.ID AND (m.STAMP IS NULL OR m.STAMP>=@Start));

SELECT COUNT(*) AS ISSUES,COUNT(DISTINCT STOCK) AS STOCKS,
    COALESCE(SUM(CASE WHEN TYPE='missing' THEN 1 ELSE 0 END),0) AS MISSING,
    COALESCE(SUM(CASE WHEN TYPE='invalid' THEN 1 ELSE 0 END),0) AS INVALID,
    COALESCE(SUM(CASE WHEN TYPE='negative' THEN 1 ELSE 0 END),0) AS NEGATIVE,
    COALESCE(SUM(CASE WHEN TYPE='opening' THEN 1 ELSE 0 END),0) AS OPENING
FROM #Issues WHERE @GroupBy='all' OR TYPE=@GroupBy;
DECLARE @Total int=(SELECT COUNT(*) FROM #Issues WHERE @GroupBy='all' OR TYPE=@GroupBy);
DECLARE @Pages int=CASE WHEN @Total=0 THEN 1 ELSE (@Total+99)/100 END;
SET @Page=CASE WHEN @Page>@Pages THEN @Pages ELSE @Page END;
SELECT @Total AS TOTAL,@Page AS PAGE,@Pages AS PAGES,
    CONVERT(bit,CASE WHEN @Export=1 AND @Total>20000 THEN 1 ELSE 0 END) AS EXPORTTOOLARGE;
SELECT * FROM #Issues
WHERE (@GroupBy='all' OR TYPE=@GroupBy) AND NOT (@Export=1 AND @Total>20000)
ORDER BY CODE,STOCK,DATE,ROWKEY
OFFSET CASE WHEN @Export=1 THEN 0 ELSE (@Page-1)*100 END ROWS
FETCH NEXT CASE WHEN @Export=1 THEN 20000 ELSE 100 END ROWS ONLY;
