SET NOCOUNT ON;
-- THOIGIANTHEM (date only) is the authoritative audit date.
-- A different or absent NGAYLAP does not constitute a cost audit issue.
SELECT s.ID,s.LOC_ID,s.ID_HANGHOA,s.ID_KHO,p.MA,p.NAME,k.NAME AS DEPOT,
    o.TUNGAY,COALESCE(o.SOLUONG,0) AS INITIAL,
    CONVERT(bit,CASE WHEN o.ID_HANGHOAKHO IS NULL THEN 0 ELSE 1 END) AS HASOPENING
INTO #Scope
FROM dbo.dm_HangHoa_Kho s
JOIN dbo.dm_HangHoa p ON p.LOC_ID=s.LOC_ID AND p.ID=s.ID_HANGHOA
LEFT JOIN dbo.dm_Kho k ON k.LOC_ID=s.LOC_ID AND k.ID=s.ID_KHO
LEFT JOIN dbo.ct_GiaVonDauKy o ON o.LOC_ID=s.LOC_ID AND o.ID_HANGHOAKHO=s.ID
WHERE s.LOC_ID=@Branch AND ISNULL(p.LOAIHANGHOA,'')<>'2'
    AND (@Depot='' OR s.ID_KHO=@Depot)
    AND (@Search='' OR CHARINDEX(@Search,p.MA)>0 OR CHARINDEX(@Search,p.NAME)>0)
    AND (@Groups='[]' OR p.ID_NHOMHANGHOA IN(SELECT value FROM OPENJSON(@Groups)));
CREATE UNIQUE CLUSTERED INDEX IX_Scope ON #Scope(ID);

SELECT d.ID_HANGHOAKHO AS STOCK,d.ID AS DETAILID,h.ID AS HEADERID,
    d.ID_PHIEUNHAP AS VOUCHERID,h.MAPHIEU AS VOUCHER,h.SOPHIEU,
    h.THOIGIANTHEM AS CREATED,h.NGAYLAP AS VOUCHERDATE,
    CONVERT(date,h.THOIGIANTHEM) AS STAMP,
    CASE WHEN t.ISNHAPTRAHANG=1 THEN 1 ELSE 0 END AS KIND,
    d.SOLUONG AS QTY,d.TYLE_QD AS RATIO,
    TRY_CONVERT(decimal(28,6),d.SOLUONG*d.TYLE_QD) AS SMALLQTY,
    CONVERT(float,NULL) AS COST,CONVERT(bit,NULL) AS COSTED,
    CONVERT(bit,CASE WHEN od.ISGIAVONDATINH=1 AND od.GIAVON>=0 AND od.SOLUONG>0 AND od.TYLE_QD>0
        AND os.ID_HANGHOA=s.ID_HANGHOA AND ot.TYPE=2 AND ot.ISTRAHANG=0
        AND NOT EXISTS(SELECT 1 FROM dbo.ct_PhieuChuyen c WHERE c.LOC_ID=d.LOC_ID AND c.ID_PHIEUXUATKHAC=oh.ID)
        THEN 1 ELSE 0 END) AS RETURNCOSTED
INTO #Moves
FROM dbo.ct_PhieuNhap_ChiTiet d
JOIN #Scope s ON s.LOC_ID=d.LOC_ID AND s.ID=d.ID_HANGHOAKHO
LEFT JOIN dbo.ct_PhieuNhap h ON h.LOC_ID=d.LOC_ID AND h.ID=d.ID_PHIEUNHAP
LEFT JOIN dbo.dm_LoaiPhieuNhap t ON t.LOC_ID=h.LOC_ID AND t.ID=h.ID_LOAIPHIEUNHAP
LEFT JOIN dbo.ct_PhieuXuat_ChiTiet od ON od.LOC_ID=d.LOC_ID AND od.ID=d.ID_PHIEUXUAT_CHITIET
LEFT JOIN dbo.dm_HangHoa_Kho os ON os.LOC_ID=od.LOC_ID AND os.ID=od.ID_HANGHOAKHO
LEFT JOIN dbo.ct_PhieuXuat oh ON oh.LOC_ID=od.LOC_ID AND oh.ID=od.ID_PHIEUXUAT
LEFT JOIN dbo.dm_LoaiPhieuXuat ot ON ot.LOC_ID=oh.LOC_ID AND ot.ID=oh.ID_LOAIPHIEUXUAT
WHERE (d.SOLUONG IS NULL OR d.SOLUONG<>0)
    AND (h.THOIGIANTHEM IS NULL OR (h.THOIGIANTHEM<@Until AND (s.TUNGAY IS NULL OR h.THOIGIANTHEM>=s.TUNGAY)))
UNION ALL
SELECT d.ID_HANGHOAKHO,d.ID,h.ID,d.ID_PHIEUXUAT,h.MAPHIEU,h.SOPHIEU,
    h.THOIGIANTHEM,h.NGAYLAP,CONVERT(date,h.THOIGIANTHEM),2,d.SOLUONG,d.TYLE_QD,
    TRY_CONVERT(decimal(28,6),d.SOLUONG*d.TYLE_QD),d.GIAVON,d.ISGIAVONDATINH,0
FROM dbo.ct_PhieuXuat_ChiTiet d
JOIN #Scope s ON s.LOC_ID=d.LOC_ID AND s.ID=d.ID_HANGHOAKHO
LEFT JOIN dbo.ct_PhieuXuat h ON h.LOC_ID=d.LOC_ID AND h.ID=d.ID_PHIEUXUAT
WHERE (d.SOLUONG IS NULL OR d.SOLUONG<>0)
    AND (h.THOIGIANTHEM IS NULL OR (h.THOIGIANTHEM<@Until AND (s.TUNGAY IS NULL OR h.THOIGIANTHEM>=s.TUNGAY)));

SELECT m.*,s.MA AS CODE,s.NAME,s.DEPOT,s.TUNGAY AS START,s.INITIAL,s.HASOPENING,
    CASE WHEN HEADERID IS NULL THEN N'Không tìm thấy phiếu cha'
        WHEN CREATED IS NULL THEN N'Thiếu THOIGIANTHEM'
        WHEN QTY IS NULL OR QTY<0 THEN N'Số lượng không hợp lệ'
        WHEN RATIO IS NULL OR RATIO<=0 OR TRY_CONVERT(decimal(18,6),RATIO) IS NULL
            OR TRY_CONVERT(decimal(18,6),RATIO)<=0 THEN N'Tỷ lệ quy đổi không hợp lệ'
        WHEN SMALLQTY IS NULL OR SMALLQTY<=0 THEN N'Số lượng quy đổi không hợp lệ'
    END AS INVALID
INTO #Checked FROM #Moves m JOIN #Scope s ON s.ID=m.STOCK;
SELECT *,
    SUM(CASE WHEN INVALID IS NULL THEN 0 ELSE 1 END) OVER(PARTITION BY STOCK) AS BADCOUNT,
    INITIAL+SUM(CASE WHEN INVALID IS NOT NULL THEN 0 WHEN KIND=2 THEN -SMALLQTY ELSE SMALLQTY END)
        OVER(PARTITION BY STOCK ORDER BY STAMP,KIND,SOPHIEU,DETAILID ROWS UNBOUNDED PRECEDING) AS BALANCE
INTO #Balance FROM #Checked;

SELECT b.STOCK,b.DETAILID,b.STAMP,CONVERT(decimal(28,10),NULL) AS UNITCOST
INTO #ReturnTargets FROM #Balance b
WHERE @GroupBy IN ('all','cost') AND b.KIND=1 AND b.RETURNCOSTED=0
    AND b.INVALID IS NULL AND b.STAMP>=@Start
    AND NOT EXISTS(SELECT 1 FROM dbo.ct_PhieuChuyen c WHERE c.LOC_ID=@Branch AND c.ID_PHIEUNHAPKHAC=b.HEADERID);
CREATE UNIQUE CLUSTERED INDEX IX_ReturnTargets ON #ReturnTargets(STOCK,DETAILID);
