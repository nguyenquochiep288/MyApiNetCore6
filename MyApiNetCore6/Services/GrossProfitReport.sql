SET NOCOUNT ON;
-- Date filter uses NGAYLAP (voucher date), not posting/creation time.
SELECT s.ID,s.ID_HANGHOA,s.ID_KHO,p.MA,p.NAME,p.ID_NHOMHANGHOA
INTO #Scope
FROM dbo.dm_HangHoa_Kho s
JOIN dbo.dm_HangHoa p ON p.LOC_ID=s.LOC_ID AND p.ID=s.ID_HANGHOA
WHERE s.LOC_ID=@Branch AND ISNULL(p.LOAIHANGHOA,'')<>'2'
  AND (@Depot='' OR s.ID_KHO=@Depot)
  AND (@Search='' OR CHARINDEX(@Search,p.MA)>0 OR CHARINDEX(@Search,p.NAME)>0)
  AND (@Groups='[]' OR p.ID_NHOMHANGHOA IN (SELECT value FROM OPENJSON(@Groups)));
CREATE UNIQUE CLUSTERED INDEX IX_Scope ON #Scope(ID);

SELECT CONCAT('X:',d.ID) AS LINEID,h.ID AS DOCID,s.ID_HANGHOA,s.ID_KHO,s.ID_NHOMHANGHOA,s.MA,s.NAME,
    h.ID_KHACHHANG,h.ID_NHANVIEN,h.MAPHIEU,h.NGAYLAP,0 AS ISRETURN,
    TRY_CONVERT(decimal(28,6),d.THANHTIEN) AS REVENUE,
    CASE WHEN d.ISGIAVONDATINH=1 AND d.GIAVON>=0 AND d.TYLE_QD>0 AND d.SOLUONG>0
        THEN TRY_CONVERT(decimal(28,6),d.SOLUONG*d.TYLE_QD*d.GIAVON) END AS COST,
    CASE WHEN d.SOLUONG>0 AND d.TYLE_QD>0 THEN TRY_CONVERT(decimal(28,6),d.SOLUONG*d.TYLE_QD) END AS QTY,
    d.ID AS DETAILID,s.ID AS STOCK,CONVERT(bit,0) AS ESTIMATED
INTO #Lines
FROM dbo.ct_PhieuXuat_ChiTiet d
JOIN dbo.ct_PhieuXuat h ON h.LOC_ID=d.LOC_ID AND h.ID=d.ID_PHIEUXUAT
JOIN dbo.dm_LoaiPhieuXuat t ON t.LOC_ID=h.LOC_ID AND t.ID=h.ID_LOAIPHIEUXUAT
JOIN #Scope s ON s.ID=d.ID_HANGHOAKHO
WHERE d.LOC_ID=@Branch AND t.TYPE=2 AND t.ISTRAHANG=0
    AND (d.SOLUONG IS NULL OR d.SOLUONG<>0) AND h.NGAYLAP>=@Start AND h.NGAYLAP<@Until
    AND NOT EXISTS(SELECT 1 FROM dbo.ct_PhieuChuyen c WHERE c.LOC_ID=@Branch AND c.ID_PHIEUXUATKHAC=h.ID)
UNION ALL
SELECT CONCAT('N:',d.ID),h.ID,s.ID_HANGHOA,s.ID_KHO,s.ID_NHOMHANGHOA,s.MA,s.NAME,
    COALESCE(oh.ID_KHACHHANG,h.ID_KHACHHANG),COALESCE(oh.ID_NHANVIEN,h.ID_NHANVIEN),h.MAPHIEU,h.NGAYLAP,1,
    TRY_CONVERT(decimal(28,6),d.THANHTIEN),
    CASE WHEN od.ISGIAVONDATINH=1 AND od.GIAVON>=0 AND od.SOLUONG>0 AND od.TYLE_QD>0
        AND os.ID_HANGHOA=s.ID_HANGHOA AND ot.TYPE=2 AND ot.ISTRAHANG=0
        AND d.SOLUONG>0 AND d.TYLE_QD>0
        AND NOT EXISTS(SELECT 1 FROM dbo.ct_PhieuChuyen c WHERE c.LOC_ID=@Branch AND c.ID_PHIEUXUATKHAC=oh.ID)
        THEN TRY_CONVERT(decimal(28,6),d.SOLUONG*d.TYLE_QD*od.GIAVON) END,
    CASE WHEN d.SOLUONG>0 AND d.TYLE_QD>0 THEN TRY_CONVERT(decimal(28,6),d.SOLUONG*d.TYLE_QD) END,
    d.ID,s.ID,CONVERT(bit,0)
FROM dbo.ct_PhieuNhap_ChiTiet d
JOIN dbo.ct_PhieuNhap h ON h.LOC_ID=d.LOC_ID AND h.ID=d.ID_PHIEUNHAP
JOIN dbo.dm_LoaiPhieuNhap t ON t.LOC_ID=h.LOC_ID AND t.ID=h.ID_LOAIPHIEUNHAP
JOIN #Scope s ON s.ID=d.ID_HANGHOAKHO
LEFT JOIN dbo.ct_PhieuXuat_ChiTiet od ON od.LOC_ID=d.LOC_ID AND od.ID=d.ID_PHIEUXUAT_CHITIET
LEFT JOIN dbo.dm_HangHoa_Kho os ON os.LOC_ID=od.LOC_ID AND os.ID=od.ID_HANGHOAKHO
LEFT JOIN dbo.ct_PhieuXuat oh ON oh.LOC_ID=od.LOC_ID AND oh.ID=od.ID_PHIEUXUAT AND os.ID_HANGHOA=s.ID_HANGHOA
LEFT JOIN dbo.dm_LoaiPhieuXuat ot ON ot.LOC_ID=oh.LOC_ID AND ot.ID=oh.ID_LOAIPHIEUXUAT
WHERE d.LOC_ID=@Branch AND t.ISNHAPTRAHANG=1
    AND (d.SOLUONG IS NULL OR d.SOLUONG<>0) AND h.NGAYLAP>=@Start AND h.NGAYLAP<@Until
    AND NOT EXISTS(SELECT 1 FROM dbo.ct_PhieuChuyen c WHERE c.LOC_ID=@Branch AND c.ID_PHIEUNHAPKHAC=h.ID);

SELECT l.STOCK,l.DETAILID,CONVERT(date,h.THOIGIANTHEM) AS STAMP,CONVERT(decimal(28,10),NULL) AS UNITCOST
INTO #ReturnTargets
FROM #Lines l
JOIN dbo.ct_PhieuNhap h ON h.LOC_ID=@Branch AND h.ID=l.DOCID
WHERE l.ISRETURN=1 AND l.COST IS NULL AND l.QTY>0 AND h.THOIGIANTHEM IS NOT NULL
    AND (@Document='' OR CONCAT('N:',l.DOCID)=@Document);
CREATE UNIQUE CLUSTERED INDEX IX_ReturnTargets ON #ReturnTargets(STOCK,DETAILID);
-- INCLUDE ReturnCostEstimates.sql
UPDATE l SET COST=e.LINECOST,ESTIMATED=1
FROM #Lines l JOIN #ReturnTargets r ON r.STOCK=l.STOCK AND r.DETAILID=l.DETAILID
CROSS APPLY (VALUES(TRY_CONVERT(decimal(28,6),l.QTY*r.UNITCOST))) e(LINECOST)
WHERE l.ISRETURN=1 AND e.LINECOST IS NOT NULL;
DROP TABLE #ReturnTargets;

SELECT l.*,
    CASE @GroupBy WHEN 'product' THEN l.ID_HANGHOA WHEN 'group' THEN ISNULL(l.ID_NHOMHANGHOA,'')
        WHEN 'customer' THEN ISNULL(l.ID_KHACHHANG,'') WHEN 'employee' THEN ISNULL(l.ID_NHANVIEN,'')
        WHEN 'depot' THEN l.ID_KHO WHEN 'voucher' THEN CONCAT(CASE WHEN l.ISRETURN=0 THEN 'X:' ELSE 'N:' END,l.DOCID) ELSE l.LINEID END AS ROWKEY,
    CASE @GroupBy WHEN 'product' THEN l.MA WHEN 'group' THEN g.MA WHEN 'customer' THEN c.MA
        WHEN 'employee' THEN e.MA WHEN 'depot' THEN k.MA WHEN 'voucher' THEN l.MAPHIEU ELSE l.MA END AS CODE,
    CASE @GroupBy WHEN 'product' THEN l.NAME WHEN 'group' THEN COALESCE(g.NAME,N'Chưa xác định nhóm')
        WHEN 'customer' THEN COALESCE(c.NAME,N'Chưa xác định khách hàng')
        WHEN 'employee' THEN COALESCE(e.NAME,N'Chưa xác định nhân viên')
        WHEN 'depot' THEN COALESCE(k.NAME,N'Chưa xác định kho')
        WHEN 'voucher' THEN CASE WHEN l.ISRETURN=0 THEN N'Phiếu xuất bán' ELSE N'Phiếu khách trả' END ELSE l.NAME END AS LABEL,
    k.NAME AS DEPOTNAME,c.NAME AS CUSTOMERNAME,e.NAME AS EMPLOYEENAME
INTO #Named FROM #Lines l
LEFT JOIN dbo.dm_NhomHangHoa g ON g.LOC_ID=@Branch AND g.ID=l.ID_NHOMHANGHOA
LEFT JOIN dbo.dm_KhachHang c ON c.LOC_ID=@Branch AND c.ID=l.ID_KHACHHANG
LEFT JOIN dbo.dm_NhanVien e ON e.LOC_ID=@Branch AND e.ID=l.ID_NHANVIEN
LEFT JOIN dbo.dm_Kho k ON k.LOC_ID=@Branch AND k.ID=l.ID_KHO
WHERE @Document='' OR CONCAT(CASE WHEN l.ISRETURN=0 THEN 'X:' ELSE 'N:' END,l.DOCID)=@Document;

SELECT ROWKEY,MAX(CODE) AS CODE,MAX(LABEL) AS NAME,
    CASE WHEN @GroupBy IN ('detail','voucher') THEN MAX(MAPHIEU) END AS VOUCHER,
    CASE WHEN @GroupBy IN ('detail','voucher') THEN MAX(NGAYLAP) END AS DATE,
    CASE WHEN @GroupBy IN ('detail','voucher') THEN MAX(DEPOTNAME) END AS DEPOT,
    CASE WHEN @GroupBy IN ('detail','voucher') THEN MAX(CUSTOMERNAME) END AS CUSTOMER,
    CASE WHEN @GroupBy IN ('detail','voucher') THEN MAX(EMPLOYEENAME) END AS EMPLOYEE,
    CASE WHEN @GroupBy IN ('detail','voucher') THEN MAX(ISRETURN) END AS ISRETURN,
    SUM(CASE WHEN ISRETURN=0 THEN REVENUE ELSE 0 END) AS SALES,
    SUM(CASE WHEN ISRETURN=1 THEN REVENUE ELSE 0 END) AS RETURNS,
    SUM(CASE WHEN ISRETURN=0 THEN REVENUE ELSE -REVENUE END) AS NET,
    SUM(CASE WHEN ISRETURN=0 THEN COST ELSE -COST END) AS NETCOST,
    SUM(CASE WHEN COST IS NULL THEN 1 ELSE 0 END) AS MISSINGCOST,
    SUM(CONVERT(int,ESTIMATED)) AS ESTIMATEDCOST,
    SUM(CASE WHEN REVENUE IS NULL THEN 1 ELSE 0 END) AS MISSINGREVENUE,
    SUM(CASE WHEN QTY IS NULL THEN 1 ELSE 0 END) AS INVALIDQTY,
    COUNT(*) AS LINES
INTO #Agg FROM #Named GROUP BY ROWKEY;

-- Null totals mean incomplete data, never silently treat missing cost as zero.
SELECT CASE WHEN COALESCE(SUM(MISSINGREVENUE),0)=0 THEN COALESCE(SUM(SALES),0) END AS SALES,
    CASE WHEN COALESCE(SUM(MISSINGREVENUE),0)=0 THEN COALESCE(SUM(RETURNS),0) END AS RETURNS,
    CASE WHEN COALESCE(SUM(MISSINGREVENUE),0)=0 THEN COALESCE(SUM(NET),0) END AS NET,
    CASE WHEN COALESCE(SUM(MISSINGCOST+INVALIDQTY),0)=0 THEN COALESCE(SUM(NETCOST),0) END AS COST,
    CASE WHEN COALESCE(SUM(MISSINGCOST+MISSINGREVENUE+INVALIDQTY),0)=0 THEN COALESCE(SUM(NET-NETCOST),0) END AS PROFIT,
    CASE WHEN COALESCE(SUM(MISSINGCOST+MISSINGREVENUE+INVALIDQTY),0)=0 AND SUM(NET)>0
        THEN (SUM(NET)-SUM(NETCOST))/SUM(NET)*100 END AS MARGIN,
    COALESCE(SUM(MISSINGCOST),0) AS MISSINGCOST,COALESCE(SUM(ESTIMATEDCOST),0) AS ESTIMATEDCOST,
    COALESCE(SUM(MISSINGREVENUE),0) AS MISSINGREVENUE,
    COALESCE(SUM(INVALIDQTY),0) AS INVALIDQTY,COALESCE(SUM(LINES),0) AS LINES FROM #Agg;

DECLARE @Total int=(SELECT COUNT(*) FROM #Agg);
DECLARE @Pages int=CASE WHEN @Total=0 THEN 1 ELSE (@Total+99)/100 END;
SET @Page=CASE WHEN @Page>@Pages THEN @Pages ELSE @Page END;
SELECT @Total AS TOTAL,@Page AS PAGE,@Pages AS PAGES,
    CONVERT(bit,CASE WHEN @Export=1 AND @Total>20000 THEN 1 ELSE 0 END) AS EXPORTTOOLARGE;
SELECT ROWKEY,CODE,NAME,VOUCHER,DATE,DEPOT,CUSTOMER,EMPLOYEE,ISRETURN,
    CASE WHEN MISSINGREVENUE=0 THEN SALES END AS SALES,
    CASE WHEN MISSINGREVENUE=0 THEN RETURNS END AS RETURNS,
    CASE WHEN MISSINGREVENUE=0 THEN NET END AS NET,
    CASE WHEN MISSINGCOST+INVALIDQTY=0 THEN NETCOST END AS COST,
    CASE WHEN MISSINGCOST+MISSINGREVENUE+INVALIDQTY=0 THEN NET-NETCOST END AS PROFIT,
    CASE WHEN MISSINGCOST+MISSINGREVENUE+INVALIDQTY=0 AND NET>0 THEN (NET-NETCOST)/NET*100 END AS MARGIN,
    MISSINGCOST,ESTIMATEDCOST,MISSINGREVENUE,INVALIDQTY,LINES
FROM #Agg WHERE NOT (@Export=1 AND @Total>20000)
ORDER BY NET DESC,ROWKEY
OFFSET CASE WHEN @Export=1 THEN 0 ELSE (@Page-1)*100 END ROWS
FETCH NEXT CASE WHEN @Export=1 THEN 20000 ELSE 100 END ROWS ONLY;
DROP TABLE #Agg;
DROP TABLE #Named;
DROP TABLE #Lines;
DROP TABLE #Scope;
